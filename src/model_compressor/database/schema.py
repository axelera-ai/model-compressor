"""Define the model compressor (MC) operator schema.

Overview
--------

The MC operator schema is a Pydantic model describing PyTorch or custom ATen operators in a way
that facilitates node annotation, graph analysis, and model compression. This schema relies on MC
types. An MC type is a Python type expression against which it is possible to validate an input or
output argument of a concrete operator invocation.

MC type grammar
---------------

An *MC type* is any Python type expression generated by the small (only three productions)
context-free grammar expressed as follows in Backus-Naur form (BNF):

    MCType ::= Literal[ <ScalarDType-member> ]               (item leaf - scalar)
             | Literal[ <TensorDType-member> ]               (item leaf - tensor)
             | list[ MCType ]                                (container node - list)

This *MC type grammar* (MC grammar) refines a subset of PyTorch's just-in-time (JIT) type grammar.
The JIT type grammar (JIT grammar) can be expressed as follows in BNF:

    JITType  ::= torch.FloatType                             (item leaf - scalar)
               | torch.IntType                               (item leaf - scalar)
               | ...                                         ...
               | torch.NoneType                              (item leaf - scalar)
               | torch.StringType                            (item leaf - scalar)
               | torch.TensorType                            (item leaf - tensor)
               | torch.DictType[ torch.StrType, JITType ]    (container node - dict)
               | torch.ListType[ JITType ]                   (container node - list)
               | torch.TupleType[ JITType, ... ]             (container node - tuple)
               | torch.OptionalType[ JITType ]               (optional node)

The MC type grammar refines JIT's TensorType into members of the TensorDType enumerated, enabling
numeric type annotation - a necessary piece of information for data-type-aware model compression.

The MC type grammar deliberately does not support dictionary and tuple container types:

* JIT's DictType does not appear in the schemas of ATen Core, whitelisted ATen non-Core, or custom
  operators - it only appears in the schemas of the overloads
  `torch.ops.aten.copy.Dict_{bool,complex,float,int,str,Tensor}` - and thus does not appear in
  MC model graphs;
* JIT's TupleType does not appear in the schemas of ATen Core, whitelisted ATen non-Core, or
  custom operators, and does not appear in MC model graphs.

The MC type grammar deliberately does not support optional types, since each MC operator
schema must minimize the ambiguity of the subgraph it represents. For instance, the JIT schema of
the `torch.ops.aten.linear.default` operator allows for an optional `"bias"` argument, a choice
that corresponds to two distinct subgraphs: one with a matrix-matrix multiplication and an
addition - `"bias"` set to `torch.TensorType` - and one with only a matrix-matrix multiplication -
`"bias"` set to `torch.NoneType`.

MC operator schema
------------------

An *MC operator schema* (MC schema) is a Pydantic model describing an ATen or custom operator with
greater precision than the corresponding PyTorch's JIT operator schema (an instance of
`torch.FunctionSchema`).

The MC schema describes:

* the computing engine where an operator is going to be executed;
* the ATen or custom operator described;
* the signature of the operator, a pair of dictionaries mapping argument names to MC types.

The MC schema validates each signature against the JIT operator schema in two stages:

* the MC schema and JIT schema define exactly the same input and output arguments;
* for each input and output, verify that
  * the MC type is well-formed (i.e., it is part of the MC type grammar);
  * the MC type is equivalent to a valid instantiation of the corresponding JIT type.

Equivalence between an MC type and an instantiation of the corresponding JIT type holds if,
after disjoining all `torch.OptionalType` occurrences in the JIT type, one of the resulting JIT
types is structurally identical to the MC type, where the following equivalences hold:

* torch.FloatType  | ScalarDType.FLOAT
* torch.IntType    | ScalarDType.INT
* ...
* torch.NoneType   | ScalarDType.NULL
* torch.StringType | ScalarDType.STRING
* torch.TensorType | TensorDType.<X>
* torch.ListType   | list

"""

import builtins
import collections
import enum
import typing
from typing import Any, Literal, NamedTuple, cast

import pydantic
import torch
import torch._ops
from typing_extensions import Self


class DType(enum.Enum):
    """A catalogue of data types."""


class ScalarDType(DType):
    """The catalogue of scalar data types."""

    BOOL = enum.auto()
    COMPLEX = enum.auto()
    DEVICE = enum.auto()
    FLOAT = enum.auto()
    GENERATOR = enum.auto()
    INT = enum.auto()
    NULL = enum.auto()
    NUMBER = enum.auto()
    STRING = enum.auto()


class TensorDType(DType):
    """The catalogue of tensor data types."""

    SI8 = enum.auto()
    SI32 = enum.auto()
    SI64 = enum.auto()
    F16 = enum.auto()
    F32 = enum.auto()


class Argument(NamedTuple):
    """A name/type pair describing an operator's input or output."""

    name: str
    type: Any


class Signature(pydantic.BaseModel):
    """A pair of ordered collections of name/type pairs describing an operator's I/O.

    Args:
        input: The ordered collection of name/input-type pairs.
        output: The ordered collection of name/output-type pairs.

    """

    model_config = pydantic.ConfigDict(arbitrary_types_allowed=True, frozen=True)
    input: list[Argument]
    output: list[Argument]

    def __hash__(self) -> int:
        # lists are unhashable but their contents are
        input = tuple(tuple(argument) for argument in self.input)
        output = tuple(tuple(argument) for argument in self.output)
        return hash((input, output))


class ComputingEngine(enum.Enum):
    """A catalogue of computing engines available on a hardware platform generation.

    !!! note

        This class is meant to be subclassed by each hardware platform generation.

    """


_JIT_SCALAR_TYPE_TO_MC_SCALAR_TYPE: dict[type[torch._C.Type], ScalarDType] = {
    cast(type[torch._C.Type], torch.BoolType): ScalarDType.BOOL,
    cast(type[torch._C.Type], torch.ComplexType): ScalarDType.COMPLEX,
    cast(type[torch._C.Type], torch.DeviceObjType): ScalarDType.DEVICE,
    cast(type[torch._C.Type], torch.FloatType): ScalarDType.FLOAT,
    cast(type[torch._C.Type], torch.IntType): ScalarDType.INT,
    cast(type[torch._C.Type], torch.NoneType): ScalarDType.NULL,
    cast(type[torch._C.Type], torch.NumberType): ScalarDType.NUMBER,
    cast(type[torch._C.Type], torch.StringType): ScalarDType.STRING,
}  # Torch stubs are incomplete, so we must ``cast`` each key
"""Map JIT scalar types to MC scalar types."""


def _check_names(where: Literal["input", "output"], expected: list[str], actual: list[str]) -> None:
    """Check that two name collections contain the same items.

    Args:
        where: Whether the names identify input or output arguments.
        expected: The reference collection of names.
        actual: The concrete collection of names.

    Raises:
        ValueError: The concrete collection has missing (underspecified) or extra (overspecified) names.
        ValueError: The concrete collection specifies names in a different order than expected.

    """
    expected_, actual_ = collections.Counter(expected), collections.Counter(actual)
    under = expected_ - actual_
    over = actual_ - expected_
    if under or over:
        raise ValueError(f"{where}: under={under}, over={over}")
    if expected != actual:
        raise ValueError(f"{where}: expected={expected}, actual={actual}")


def _check_mc_type(where: str, mc_type: Any) -> None:
    """Check that a type expression is a well-formed MC type.

    Args:
        where: The argument's name.
        mc_type: The expression candidate to be an MC type.

    Raises:
        ValueError: The list type expression (node) does not contain exactly one argument.
        ValueError: The literal type expression (leaf) does not contain exactly one argument.
        ValueError: The argument to the literal type expression (leaf) is not a scalar enumerated
            or tensor numerics enumerated.
        ValueError: The type expression is not a list nor a literal.

    """
    origin = typing.get_origin(mc_type)
    match origin:
        case builtins.list:
            arguments = typing.get_args(mc_type)
            argument, *others = arguments
            if len(others) > 0:
                raise ValueError(f"{where}: 'list[ MCType ]' requires exactly one argument, got {arguments!r}")
            _check_mc_type(f"{where}[]", argument)
            return
        case typing.Literal:
            arguments = typing.get_args(mc_type)
            argument, *others = arguments
            if len(others) > 0:
                raise ValueError(f"{where}: 'Literal[ <member> ]' requires exactly one argument, got {arguments!r}")
            if not isinstance(argument, (ScalarDType, TensorDType)):
                raise ValueError(
                    f"{where}: the argument for 'Literal[ <member> ]' must be a ScalarDType or TensorDType member, got {argument!r}"
                )
            return
        case _:
            raise ValueError(
                f"{where}: not an MC type; expected one of 'list[ MCType ]' or 'Literal[ <member> ]', got {mc_type!r}"
            )


def _check_mc_type_against_jit_type(where: str, mc_type: Any, jit_type: torch._C.Type) -> None:
    """Check that an MC type is equivalent to a JIT type.

    Args:
        where: The argument's name.
        mc_type: The argument's MC type.
        jit_type: The argument's JIT type.

    """
    match type(jit_type):
        case torch.DictType:
            raise ValueError(f"{where}: JIT type {jit_type!r} has no MC type counterpart (see module docstring)")
        case torch.ListType:
            origin = typing.get_origin(mc_type)
            (argument,) = typing.get_args(mc_type)
            if origin is not list:
                raise ValueError(
                    f"{where}: JIT type {jit_type!r} must map to a 'list[ MCType ]' MC type, got {mc_type!r}"
                )
            _check_mc_type_against_jit_type(f"{where}[]", argument, jit_type.getElementType())
            return
        case torch.TupleType:
            raise ValueError(f"{where}: JIT type {jit_type!r} has no MC type counterpart (see module docstring)")
        case torch.OptionalType:
            if mc_type != Literal[ScalarDType.NULL]:
                _check_mc_type_against_jit_type(where, mc_type, jit_type.getElementType())
            return
        case torch.TensorType:
            origin = typing.get_origin(mc_type)
            (argument,) = typing.get_args(mc_type)
            if origin is not Literal:
                raise ValueError(
                    f"{where}: JIT type {jit_type!r} must map to a 'Literal [ <TensorDType-member> ]', got {origin!r}"
                )
            if not isinstance(argument, TensorDType):
                raise ValueError(
                    f"{where}: JIT type {jit_type!r} requires a 'Literal[ <TensorDType-member> ]', got Literal[{argument!r}]"
                )
            return
        case _:
            origin = typing.get_origin(mc_type)
            (argument,) = typing.get_args(mc_type)
            if origin is not Literal:
                raise ValueError(
                    f"{where}: JIT type {jit_type!r} must map to a 'Literal [ <ScalarDType-member> ]', got {origin!r}"
                )
            if not isinstance(argument, ScalarDType):
                raise ValueError(
                    f"{where}: JIT type {jit_type!r} requires a 'Literal[ <ScalarDType-member> ]', got Literal[{argument!r}]"
                )
            if argument != (expected_argument := _JIT_SCALAR_TYPE_TO_MC_SCALAR_TYPE[type(jit_type)]):
                raise ValueError(
                    f"{where}: JIT type {jit_type!r} requires Literal[{expected_argument!r}], got Literal[{argument!r}]"
                )
            return


class Schema(pydantic.BaseModel):
    """A JIT-validated MC operator schema.

    Args:
        engine: The computing engine where the operator executes.
        target: The operator - an ATen or custom ``OpOverload``.
        signature: The ordered name/type pair collections describing the operator's I/O.
        metadata: A Markdown string with implementation notes.

    """

    model_config = pydantic.ConfigDict(arbitrary_types_allowed=True, frozen=True)
    engine: ComputingEngine
    target: torch._ops.OpOverload
    signature: Signature
    metadata: str

    @pydantic.model_validator(mode="after")
    def _validate_signature(self) -> Self:
        """Verify that the signature is well-formed and consistent with the operator's JIT schema."""
        jit_schema = self.target._schema
        # check the input signature
        _check_names(
            where="input",
            expected=[argument.name for argument in jit_schema.arguments],
            actual=[argument.name for argument in self.signature.input],
        )
        for jit_argument, mc_argument in zip(jit_schema.arguments, self.signature.input, strict=True):
            where = f"input[{jit_argument.name!r}]"
            _check_mc_type(where, mc_argument.type)
            _check_mc_type_against_jit_type(where, mc_argument.type, cast(torch._C.Type, jit_argument.type))
        # check the output signature
        _check_names(
            where="output",
            expected=[argument.name for argument in jit_schema.returns],
            actual=[argument.name for argument in self.signature.output],
        )
        for jit_argument, mc_argument in zip(jit_schema.returns, self.signature.output, strict=True):
            where = f"output[{jit_argument.name!r}]"
            _check_mc_type(where, mc_argument.type)
            _check_mc_type_against_jit_type(where, mc_argument.type, cast(torch._C.Type, jit_argument.type))
        return self


__all__ = ["DType", "ScalarDType", "TensorDType", "Argument", "Signature", "ComputingEngine", "Schema"]
